import { chromium, webkit, devices, expect as baseExpect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const expect = baseExpect.configure({ timeout: 60000 });
const base = process.env.ACADEMY_AUDIT_URL || "http://localhost:3015";
const out = path.resolve("test-results/csharp-methods");
await mkdir(out, { recursive: true });
const report = { scope: "Synthetic isolated previews, no learner account or physical iPhone keyboard", profiles: [], errors: [] };
const profiles = [
  ["desktop", chromium, { viewport: { width: 1366, height: 768 } }],
  ["iphone-webkit", webkit, { ...devices["iPhone 13"], viewport: { width: 390, height: 664 } }],
  ["narrow-webkit", webkit, { ...devices["iPhone SE"], viewport: { width: 320, height: 640 } }],
];
try {
  for (const [name, engine, options] of profiles.filter(([name]) => !process.env.ACADEMY_AUDIT_PROFILE || name === process.env.ACADEMY_AUDIT_PROFILE)) {
    const browser = await engine.launch();
    try {
      const context = await browser.newContext({ ...options, reducedMotion: "reduce" });
      const page = await context.newPage();
      page.on("pageerror", error => report.errors.push({ name, error: String(error) }));
      page.setDefaultTimeout(60000);
      const result = { name, checks: [] }; report.profiles.push(result);
      await page.goto(base + "/dev/csharp-preview?academy=1&view=methods", { waitUntil: "domcontentloaded", timeout: 120000 });
      const unit = page.locator("[data-csharp-methods]");
      await expect(unit).toBeVisible();
      await expect(unit.getByRole("heading", { name: "Uma regra. Vários clientes." })).toBeVisible();
      await expect(unit).toContainText("Execute no computador com SDK .NET 10");
      await page.evaluate(() => scrollTo(0, 0));
      const start = unit.getByRole("button", { name: "Começar a tarefa", exact: true });
      const box = await start.boundingBox();
      result.firstFold = box;
      expect(box.y + box.height).toBeLessThan(options.viewport.height - (options.isMobile ? 64 : 0));
      const scene = await unit.locator("img").boundingBox();
      expect(Math.min(scene.y + scene.height, options.viewport.height) - Math.max(scene.y, 0)).toBeGreaterThan(70);
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(options.viewport.width);
      const zip = await context.request.get(base + "/downloads/academy/orbiservicos-metodos-v1.zip");
      expect(zip.ok()).toBe(true); expect((await zip.body()).subarray(0, 2).toString()).toBe("PK");
      await expect.poll(() => unit.locator("img").evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
      await expect.poll(() => unit.locator("img").evaluate(img => !img.style.backgroundImage)).toBe(true);
      await page.screenshot({ path: path.join(out, name + "-entry.png") });
      await start.click();
      await expect.poll(async () => (await unit.getByRole("heading", { level: 1 }).boundingBox()).y).toBeGreaterThanOrEqual(64);
      const editor = unit.getByRole("textbox", { name: "Seu rascunho C#", exact: true });
      await expect(editor).toHaveValue("");
      await expect(unit.getByRole("button", { name: /Executar/ })).toHaveCount(0);
      await unit.getByText("Casos para comparar no computador", { exact: true }).click();
      await expect(unit.getByText("Outro segundo valor", { exact: true })).toHaveCount(0);
      await unit.getByRole("radio", { name: "3", exact: true }).check();
      await expect(unit.getByText("Outro segundo valor", { exact: true })).toBeVisible();
      await unit.getByText("Ver exemplo e caminho do valor", { exact: true }).click();
      await unit.getByRole("button", { name: "Usar exemplo no rascunho", exact: true }).click();
      await expect(editor).toHaveValue(/CalcularPendentes/);
      await unit.getByRole("button", { name: "Preciso de uma pista", exact: true }).click();
      await expect(unit).toContainText("Você consultou ajuda");
      await unit.getByRole("button", { name: "Registrar que executei no PC", exact: true }).click();
      await expect(unit).toContainText("resultado não conferido pela plataforma");
      await editor.fill("// tentativa nova\nint pendentes = 3;");
      await expect(unit.getByRole("button", { name: "Remover minha declaração", exact: true })).toHaveCount(0);
      await unit.getByRole("button", { name: "Limpar rascunho", exact: true }).click();
      await unit.getByRole("button", { name: "Confirmar substituição", exact: true }).click();
      await expect(editor).toHaveValue("");
      await unit.getByRole("button", { name: "Recuperar texto anterior", exact: true }).click();
      await expect(editor).toHaveValue("// tentativa nova\nint pendentes = 3;");
      await page.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: () => Promise.reject(new Error("QA: clipboard denied")) } }));
      await unit.getByRole("button", { name: "Copiar para Program.cs", exact: true }).click();
      await expect(unit).toContainText("Não foi possível copiar automaticamente");
      await expect(editor).toBeFocused();
      await page.waitForTimeout(350);
      await page.reload({ waitUntil: "domcontentloaded" });
      await expect(editor).toHaveValue("// tentativa nova\nint pendentes = 3;");
      await expect(unit).toContainText("Você consultou ajuda");
      await unit.getByText("Levar o rascunho para outro aparelho", { exact: true }).click();
      const downloadEvent = page.waitForEvent("download");
      await unit.getByRole("button", { name: "Exportar rascunho", exact: true }).click();
      const download = await downloadEvent;
      const exported = JSON.parse(await readFile(await download.path(), "utf8"));
      expect(exported.text).toBe("// tentativa nova\nint pendentes = 3;");
      expect(Object.keys(exported).sort()).toEqual(["format", "version", "unitId", "activityId", "filename", "text"].sort());
      const payload = { format: "orbitamos-csharp-methods-draft", version: 1, unitId: "orbiservicos-methods-v1", activityId: "guided", filename: "Program.cs", text: "// importado\nConsole.WriteLine(8);" };
      await unit.locator('input[type="file"]').setInputFiles({ name: "rascunho.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(payload)) });
      await expect(editor).toHaveValue("// tentativa nova\nint pendentes = 3;");
      await unit.getByRole("button", { name: "Cancelar importação", exact: true }).click();
      await unit.locator('input[type="file"]').setInputFiles({ name: "rascunho.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(payload)) });
      await editor.fill("// edição feita enquanto arquivo aguardava");
      await unit.getByRole("button", { name: "Confirmar importação", exact: true }).click();
      await expect(editor).toHaveValue(payload.text);
      await unit.getByRole("button", { name: "Recuperar texto anterior", exact: true }).click();
      await expect(editor).toHaveValue("// edição feita enquanto arquivo aguardava");
      await unit.getByRole("button", { name: "Escrever código ↓", exact: true }).click();
      await expect(editor).toBeFocused();
      expect(await editor.evaluate(element => getComputedStyle(element).fontSize)).toBe("16px");
      await page.screenshot({ path: path.join(out, name + "-editor.png") });
      const axe = await new AxeBuilder({ page }).include("[data-csharp-methods]").withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
      result.accessibility = axe.violations.map(({ id, impact, nodes }) => ({ id, impact, count: nodes.length }));
      expect(result.accessibility).toEqual([]);
      await unit.getByRole("button", { name: "Explorar próxima tarefa", exact: true }).click();
      await expect(unit).toContainText("Uma regra, três clientes"); await expect(editor).toHaveValue("");
      await unit.getByRole("button", { name: "Usar assinatura inicial", exact: true }).click();
      await expect(editor).toHaveValue("int CalcularPendentes(int total, int concluidos)\n{\n\n}");
      await unit.getByRole("button", { name: "Explorar próxima tarefa", exact: true }).click();
      await unit.getByRole("button", { name: "Usar bug preparado", exact: true }).click();
      await expect(editor).toHaveValue(/return 5;/);
      await unit.getByRole("button", { name: "Explorar próxima tarefa", exact: true }).click();
      await expect(editor).toHaveValue("");
      await expect(unit.getByRole("button", { name: /Usar.*rascunho/ })).toHaveCount(0);
      await expect(unit).toContainText("bool PodeIniciar(int pendentes, bool pago)");
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(options.viewport.width);
      await page.screenshot({ path: path.join(out, name + "-independent.png") });
      await editor.fill("// exercício independente");
      await page.waitForTimeout(350);
      await page.goto(base + "/dev/csharp-preview?view=methods", { waitUntil: "domcontentloaded" });
      await expect(unit.getByRole("heading", { name: "Uma regra. Vários clientes." })).toBeVisible();
      await unit.getByRole("button", { name: "Começar a tarefa", exact: true }).click();
      await expect(editor).toHaveValue("");
      await expect(unit).toContainText("Nenhuma consulta à ajuda registrada");
      await page.goto(base + "/dev/csharp-preview?academy=1&view=methods", { waitUntil: "domcontentloaded" });
      await expect(editor).toHaveValue("// exercício independente");
      await page.goto(base + "/dev/academy-preview?view=home", { waitUntil: "domcontentloaded" });
      await expect(page.locator("[data-academy-continue]")).toContainText("Uma regra que você pode reutilizar");
      await expect(page.locator('[data-academy-continue] a[href="/dev/csharp-preview?academy=1&view=methods"]')).toBeVisible();
      await page.goto(base + "/dev/academy-preview?view=progress", { waitUntil: "domcontentloaded" });
      await expect(page.locator("[data-csharp-methods-record]")).toBeVisible();
      await expect(page.locator("[data-csharp-methods-record]")).toContainText("nenhum resultado conferido");
      result.checks.push("Entry/photo/SDK notice/ZIP, empty drafts, prediction, sticky help, self-report invalidation, confirmed reset/undo and import latest backup, reload, four tasks, exact continuation and separate progress, no horizontal overflow");
      await context.close();
      console.log(name + " passed");
    } finally { await browser.close(); }
  }
  expect(report.errors).toEqual([]); report.completed = true;
} finally { await writeFile(path.join(out, "report.json"), JSON.stringify(report, null, 2)); }
