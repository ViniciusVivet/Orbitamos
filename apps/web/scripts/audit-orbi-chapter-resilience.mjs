import { chromium, expect } from "@playwright/test";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
const base=process.env.ORBI_TEST_URL || "http://localhost:3015";
const output="test-results/orbi-chapter";
await mkdir(output,{recursive:true});
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:"reduce"});
const page=await context.newPage();
page.setDefaultTimeout(30000);
const errors=[];page.on("pageerror",e=>errors.push(e.message));
const key="orbitamos-orbi-chapter-v2-academy-preview";
try{
 await page.goto(base+"/dev/academy-preview?activity=delivery",{waitUntil:"domcontentloaded",timeout:180000});
 await page.getByRole("button",{name:"Entrar no bairro"}).click();
 const stage=page.locator("[data-orbi-chapter-canvas]");
 await expect(stage).toHaveAttribute("data-player-x",/\d+/);
 await stage.focus();await page.keyboard.down("ArrowRight");
 await expect.poll(async()=>Number(await stage.getAttribute("data-player-x")),{intervals:[30]}).toBeGreaterThan(430);
 await page.keyboard.up("ArrowRight");
 await page.getByRole("button",{name:"Abrir terminal"}).click();
 const dialog=page.getByRole("dialog"),code=dialog.getByRole("textbox",{name:"Seu código"});
 await code.fill("const alcance = 280;");
 const other=await context.newPage();await other.goto(base+"/dev/academy-preview?view=home",{waitUntil:"domcontentloaded",timeout:180000});
 await other.evaluate(key=>{
   const saved=JSON.parse(localStorage.getItem(key));saved.completed=["ponte"];saved.current="elevador";localStorage.setItem(key,JSON.stringify(saved));
 },key);
 await page.bringToFront();
 await code.fill("const alcance = 300;");
 assert.deepEqual(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)).completed,key),["ponte"],"Stale tab cannot erase another tab's completion");
 await page.evaluate(key=>{
  window.orbiOriginalSetItem=Storage.prototype.setItem;
  Storage.prototype.setItem=function(k,v){if(k===key)throw new DOMException("quota","QuotaExceededError");return window.orbiOriginalSetItem.call(this,k,v);};
 },key);
 await code.fill("const alcance = 290;");
 await expect(dialog.getByRole("alert")).toContainText("não conseguiu guardar");
 assert.equal(await code.inputValue(),"const alcance = 290;","Memory draft remains editable when storage fails");
 await page.screenshot({path:output+"/mobile-storage-warning.png",fullPage:true});
 await page.evaluate(()=>{Storage.prototype.setItem=window.orbiOriginalSetItem;delete window.orbiOriginalSetItem;});
 await code.fill("const alcance = 280;");
 await dialog.getByRole("button",{name:"Aplicar e ver no cenário"}).click();
 const resume=page.getByRole("button",{name:"Continuar aventura",exact:true});
 if(await resume.isVisible())await resume.click();
 const right=page.getByRole("button",{name:"Caminhar para a direita"}),jump=page.getByRole("button",{name:/^Pular/});
 await right.scrollIntoViewIfNeeded();
 const a=await right.boundingBox(),b=await jump.boundingBox();
 const point=(box,id)=>({x:box.x+box.width/2,y:box.y+box.height/2,id,radiusX:8,radiusY:8,force:1});
 const cdp=await context.newCDPSession(page);
 const before=Number(await stage.getAttribute("data-player-x"));
 await cdp.send("Input.dispatchTouchEvent",{type:"touchStart",touchPoints:[point(a,1)]});
 await page.waitForTimeout(200);
 await cdp.send("Input.dispatchTouchEvent",{type:"touchStart",touchPoints:[point(a,1),point(b,2)]});
 await cdp.send("Input.dispatchTouchEvent",{type:"touchEnd",touchPoints:[point(a,1)]});
 await expect.poll(async()=>Number(await stage.getAttribute("data-player-y"))).toBeLessThan(420);
 await expect.poll(async()=>Number(await stage.getAttribute("data-player-x"))).toBeGreaterThan(before+30);
 await cdp.send("Input.dispatchTouchEvent",{type:"touchEnd",touchPoints:[]});
 await page.waitForTimeout(250);const stopped=Number(await stage.getAttribute("data-player-x"));
 await page.waitForTimeout(250);assert(Math.abs(Number(await stage.getAttribute("data-player-x"))-stopped)<3,"Releasing touch stops movement");
 await page.screenshot({path:output+"/mobile-touch-controls.png",fullPage:true});
 assert.deepEqual(errors,[]);
 const result={staleTabPreservesAchievement:true,quotaWarningInsideTerminal:true,draftRetainedInMemory:true,multitouchMovementAndJump:true,touchReleaseStopsMovement:true,errors};
 await writeFile(output+"/edge-results.json",JSON.stringify(result,null,2));console.log(result);
}finally{await context.close();await browser.close();}
